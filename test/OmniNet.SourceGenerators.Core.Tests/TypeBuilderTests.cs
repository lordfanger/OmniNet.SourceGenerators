    [Test]
    public async Task ComplexClassWithMultipleMembers_GeneratesCorrectSyntax()
    {
        var code = GetGeneratedCode(sb =>
        {
            using var type = sb.BuildClass("PersonService")
                .WithAccessibility(Accessibility.Public)
                .WithPartial()
                .Append()
                .AppendOpenType();

            TypeReference stringType = "string";
            TypeReference intType = "int";
            TypeReference boolType = "bool";

            type.BuildProperty(stringType, "Name")
                .WithAccessibility(Accessibility.Public)
                .WithRequired()
                .WithImplicitGetter()
                .WithImplicitSetter(initOnly: true)
                .Append();

            type.BuildProperty(intType, "Age")
                .WithAccessibility(Accessibility.Public)
                .WithImplicitGetter()
                .WithImplicitSetter()
                .Append();

            type.BuildMethod("IsAdult", boolType)
                .WithAccessibility(Accessibility.Public)
                .OpenParameters()
                .AppendExpression("Age >= 18");
        });

        await Assert.That(code).IsEqualTo("""
            public partial class PersonService
            {
            	public required string Name { get; init; }
            
            	public int Age { get; set; }
            
            	public bool IsAdult() => Age >= 18;
            }
            """.UnifyCodeLineEndings());
    }
