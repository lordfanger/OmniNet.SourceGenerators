    private static string GetGeneratedCode(Action<SourceBuilder> buildAction)
    {
        const string prefix = "// <auto-generated/>\r\n#nullable enable\r\n\r\n";
        const string suffix = "\r\n";

        var sb = new SourceBuilder();
        buildAction(sb);
        
        var code = sb.GetOutputForTesting();
        if (code.StartsWith(prefix) && code.EndsWith(suffix))
        {
            code = code.Substring(prefix.Length, code.Length - prefix.Length - suffix.Length);
        }

        return code.UnifyCodeLineEndings();
    }

    [Test]
    public async Task EmptyClass_GeneratesCorrectSyntax()
    {
        var code = GetGeneratedCode(sb =>
        {
            using var type = sb.BuildClass("TestClass")
                .WithAccessibility(Accessibility.Public)
                .Append()
                .AppendOpenType();
        });

        await Assert.That(code).IsEqualTo("""
            public class TestClass
            {
            }
            """.UnifyCodeLineEndings());
    }

